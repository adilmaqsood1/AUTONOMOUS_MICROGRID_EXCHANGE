from collections import defaultdict
from datetime import datetime, timedelta
from decimal import Decimal

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.agents.base import Intent, MarketObservation
from app.agents.battery import BatteryAgent
from app.agents.ev import EVAgent
from app.agents.participants import CommercialAgent, ConsumerAgent, GeneratorAgent, GenerationView, GridAgent, ProsumerAgent
from app.core.enums import AgentAction, AssetStatus, AssetType, LoadPriority, OperatingMode, OrderSide, ParticipantType
from app.forecasting.service import demand_forecast, generation_forecast
from app.market.service import create_order
from app.models.assets import EnergyAsset
