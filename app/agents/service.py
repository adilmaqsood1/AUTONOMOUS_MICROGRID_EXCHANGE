from app.risk.service import battery_state, ev_state, reserve_policy
from app.simulation import scenarios, signals
from app.simulation.state import SimConfig, get_config

D = lambda x: Decimal(str(round(float(x), 6)))  # noqa: E731


async def observation(session: AsyncSession, mg: Microgrid, ws: datetime, we: datetime, cfg: SimConfig) -> MarketObservation:
    mods = await scenarios.active_modifiers(session, mg.id, ws, we)
    tz = cfg.tz_offset_hours
    imp = D(signals.utility_price(ws, tz, mods.price_multiplier))
    exp = D(signals.export_price(ws, tz, mods.price_multiplier))
    horizon = [(D(signals.utility_price(ws + timedelta(hours=i), tz)) + D(signals.export_price(ws + timedelta(hours=i), tz))) / 2
               for i in range(24)]
    cur = (imp + exp) / 2
    return MarketObservation(ws, we, imp, exp, cur, max(horizon + [cur]), min(horizon + [cur]),
                             mg.external_grid_connected, mg.operating_mode != OperatingMode.GRID_CONNECTED.value)


async def run_agents(session: AsyncSession, microgrid_id: uuid.UUID, ws: datetime, we: datetime,
                     actor: str = "agent_runner", now: datetime | None = None) -> dict:
    mg = await session.get(Microgrid, microgrid_id)
    cfg = await get_config(session, microgrid_id)
    now = now or cfg.sim_time
    m = await observation(session, mg, ws, we, cfg)
    hours = m.hours
    parts = list((await session.execute(select(Participant).where(Participant.microgrid_id == microgrid_id, Participant.active.is_(True))
                                        .order_by(Participant.name))).scalars())
    assets = list((await session.execute(select(EnergyAsset).where(EnergyAsset.microgrid_id == microgrid_id)
                                         .order_by(EnergyAsset.name))).scalars())
    by_p: dict[uuid.UUID, list[EnergyAsset]] = defaultdict(list)
    for a in assets:
        by_p[a.participant_id].append(a)

    gen_fc: dict[uuid.UUID, object] = {}
    dem_fc: dict[uuid.UUID, object] = {}
    for a in assets:
        if a.generator and a.generator.renewable and a.status == AssetStatus.ONLINE.value:
            gen_fc[a.id] = await generation_forecast(session, a, ws, we, now, cfg)
        if a.load:
            dem_fc[a.id] = await demand_forecast(session, a, ws, we, now, cfg)
    total_gen = sum(f.predicted_value for f in gen_fc.values())
    total_dem = sum(f.predicted_value for f in dem_fc.values())
    surplus, deficit = max(0.0, total_gen - total_dem), max(0.0, total_dem - total_gen)
    policy = reserve_policy()

    intents: list[tuple[Intent, EnergyAsset | None]] = []
    for p in parts:
        mine = by_p[p.id]
        handled_prosumer = False
        if p.type == ParticipantType.PROSUMER.value:
            gens = [a for a in mine if a.id in gen_fc]
            lds = [a for a in mine if a.load]
            if gens and lds:
                pg = sum(gen_fc[a.id].predicted_value for a in gens)
                lg = sum(gen_fc[a.id].lower_bound for a in gens)
                dem = sum(dem_fc[a.id].predicted_value for a in lds)
                room = sum(max(0.0, a.battery.capacity_kwh * a.battery.maximum_soc_percent / 100 -
                               battery_state(a).stored_kwh) for a in mine if a.battery)
                mc = min(a.generator.marginal_cost for a in gens)
                for it in ProsumerAgent(policy).decide(str(p.id), str(gens[0].id), str(lds[0].id), pg, lg, dem, m, room, mc):
                    asset = gens[0] if it.action in (AgentAction.SELL, AgentAction.STORE, AgentAction.HOLD) else lds[0]
                    intents.append((it, asset))
                handled_prosumer = True
        for a in mine:
            pid = str(p.id)
            if a.asset_type == AssetType.GRID_CONNECTION.value:
                for it in GridAgent().decide(pid, str(a.id), mg.max_grid_import_kw, mg.max_grid_export_kw, m):
                    intents.append((it, a))
            elif a.generator and not handled_prosumer:
                f = gen_fc.get(a.id)
                g = a.generator
                if g.renewable and f is None:
                    intents.append((Intent("GeneratorAgent", pid, str(a.id), AgentAction.HOLD,
                                           reason_codes=["ASSET_UNAVAILABLE"], inputs={"status": a.status}), a))
                    continue
                pred = f.predicted_value if f else g.maximum_generation_kw * hours
                low = f.lower_bound if f else pred
                view = GenerationView(a.rated_power_kw, g.maximum_generation_kw, g.marginal_cost, g.renewable, pred, low,
                                      a.status == AssetStatus.ONLINE.value)
                intents.append((GeneratorAgent(policy).decide(pid, str(a.id), view, m), a))
            elif a.battery:
                intents.append((BatteryAgent(p.preferences.get("reserve_extra_percent", 10.0)).decide(
                    pid, str(a.id), battery_state(a), m, surplus, deficit), a))
            elif a.ev:
                intents.append((EVAgent().decide(pid, str(a.id), ev_state(a), m, deficit), a))
            elif a.load and not handled_prosumer:
                dem = dem_fc[a.id].predicted_value
                if a.load.load_kind == "COMMERCIAL":
                    frac = min(1.0, a.load.maximum_curtailment_kw / max(a.load.current_demand_kw, 1e-6)) if a.load.flexible else 0.0
                    for it in CommercialAgent().decide(pid, str(a.id), dem, frac, m):
                        intents.append((it, a))
                else:
                    intents.append((ConsumerAgent().decide(pid, str(a.id), dem, m, a.load.flexible,
                                                           bool(p.preferences.get("renewable_only"))), a))

    created, decisions = [], []
    for it, asset in intents:
        side = {AgentAction.BUY: OrderSide.BUY, AgentAction.CHARGE: OrderSide.BUY,
                AgentAction.SELL: OrderSide.SELL, AgentAction.DISCHARGE: OrderSide.SELL}.get(it.action)
        order = None
        info = it.explanation()
        if side and it.quantity_kwh > 0 and it.limit_price and it.limit_price > 0 and asset is not None:
            order = await create_order(session, uuid.UUID(it.participant_id), asset.id, side, it.quantity_kwh,
                                       it.limit_price, ws, we, it.renewable_only, f"agent:{it.agent}", now)
            info["order_id"], info["order_status"] = str(order.id), order.status
            created.append(order)
        session.add(DecisionRecord(microgrid_id=microgrid_id, actor=it.agent, decision=it.action.value,
                                   quantity_kwh=float(it.quantity_kwh), reason_codes={"codes": it.reason_codes},
                                   inputs=info.get("inputs", {}) | {"participant_id": it.participant_id,
                                                                    "order_id": info.get("order_id")}, created_at=now))
        decisions.append(info)
    await session.flush()
    return {"orders": created, "decisions": decisions}
